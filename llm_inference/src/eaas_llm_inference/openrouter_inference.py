"""One prompt, one OpenRouter inference request, one answer.

Setup: uv sync
Configuration is read from the project's private .env file at runtime.
Run from the project root: uv run openrouter-inference
Get a key: https://openrouter.ai/workspaces/default/keys
HTTP basics: ../../http_and_requests.md (from the package directory)
Walkthrough: ../../openrouter_walkthrough.md (from the package directory)
"""

from pathlib import Path
from typing import Any

import requests  # General-purpose HTTP library, independent of OpenRouter.
from dotenv import dotenv_values  # Read a local configuration file.


def main() -> None:
    """Send one prompt to OpenRouter and print the generated answer."""
    # Type hints such as ": Path" or "-> None" document what a name holds or a
    # function returns. Python does not check them at runtime.

    # In this editable course checkout, this file is in src/eaas_llm_inference/.
    # parents[0] is the package folder, [1] is src, [2] is the project root.
    project_root: Path = Path(__file__).resolve().parents[2]
    env_path: Path = project_root / ".env"

    # Parse the file into a dictionary; the process environment stays unchanged.
    # A value is None when the file has a name without "=".
    config: dict[str, str | None] = dotenv_values(env_path, interpolate=False)
    api_key: str | None = config.get("OPENROUTER_API_KEY")  # None if absent.
    if api_key is None or not api_key.strip():
        raise SystemExit("OPENROUTER_API_KEY is missing from the local configuration.")
    # The key is now plain text in memory. A paused debugger shows api_key and
    # config, which holds every key in .env, under Variables > Locals without
    # any expanding: keep that panel off shared screens and screenshots.

    prompt: str = "Explain tokenization in one sentence."

    # This call sends HTTPS to OpenRouter, which forwards the request to a
    # provider, where the model runs: for this free model, currently NVIDIA.
    # Local Python waits here for the response. No model is loaded locally.
    # Requests adds its default headers (User-Agent, Accept, ...) to ours,
    # encodes json= as UTF-8 bytes and returns once the whole body has arrived.
    print("Sending request to OpenRouter; waiting for the response...")
    response: requests.Response = requests.post(
        "https://openrouter.ai/api/v1/chat/completions",
        headers={"Authorization": f"Bearer {api_key}"},  # Send the selected value.
        json={  # Serialized into the JSON request body.
            # ":free" selects the free variant; NVIDIA is currently its only provider.
            "model": "nvidia/nemotron-3.5-lightning:free",
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": 256,  # Upper limit on generated tokens, not words.
            "temperature": 1.0,
            "top_p": 0.95,
            "stream": False,  # Receive the complete response at once.
            # OpenRouter's own switch. NVIDIA's chat_template_kwargs is not part
            # of OpenRouter's documented API.
            "reasoning": {"enabled": False},
        },
        # The next two arguments configure Requests locally; they are not sent.
        timeout=60,
        allow_redirects=False,
    )
    # response is a local Requests object that wraps OpenRouter's HTTP answer:
    #   status_code, reason, headers  HTTP status line and headers from OpenRouter
    #   content                       body as raw bytes (JSON text, not parsed)
    #   elapsed                       measured on this laptop until headers arrived;
    #                                 OpenRouter sends them before the first token
    #   request                       the request we sent, including the key
    # Only the message text inside the body was generated by the model.
    print(f"Received HTTP {response.status_code} from OpenRouter.")

    # Back on the laptop: check, parse and display. These steps do no inference.
    # On an error status, OpenRouter explains the reason in the body; the
    # exception raised below would only name the status code.
    if not response.ok:
        print(response.text)
    response.raise_for_status()  # Raise for an HTTP error (4xx/5xx).
    # Parse the body bytes into Python dicts and lists. The body is already
    # stored locally, so this does not contact OpenRouter again.
    result: dict[str, Any] = response.json()
    # OpenRouter sends "200 OK" as soon as the provider accepts the request,
    # before the first token. A provider failure after that is reported in the
    # body: as "error" instead of "choices", or as "error" in choices[0] beside
    # partial output.
    if "error" in result:
        raise SystemExit(f"OpenRouter reported an error: {result['error']}")
    if "error" in result["choices"][0]:
        raise SystemExit(
            f"OpenRouter reported an error: {result['choices'][0]['error']}"
        )
    # Besides choices, the body typically holds id, model, provider and usage
    # (token counts and cost). Each choice has a finish_reason ("stop", or
    # "length" at max_tokens) and a message whose content is the generated text.
    print(result["choices"][0]["message"]["content"])


if __name__ == "__main__":
    main()
